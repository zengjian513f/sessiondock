"""Real filesystem + keyboard paths shared by SDK and ordinary composers."""
from playwright.sync_api import expect


def create_paths(work):
    (work / '路径目录').mkdir(exist_ok=True)
    (work / '路径目录' / '中文 report.txt').write_text('synthetic input\n')
    (work / '路径目录' / '另一个.md').write_text('synthetic input\n')
    (work / 'readme-one.md').write_text('one\n')
    (work / 'readme-two.md').write_text('two\n')
    (work / '.hidden-note').write_text('hidden\n')
    (work / 'linked-dir').symlink_to(work / '路径目录', target_is_directory=True)


def exercise_paths(page, editor, work, screenshot=None):
    popup = page.locator('[aria-label="路径补全"]')
    editor.fill('请检查 ./路径')
    editor.press('Tab')
    expect(editor).to_have_value('请检查 ./路径目录/')
    editor.press('Tab')
    expect(popup.get_by_role('option')).to_have_count(2)
    if screenshot:
        page.screenshot(path=str(screenshot))
    editor.press('Tab')
    editor.press('Shift+Tab')
    editor.press('ArrowDown')
    editor.press('ArrowUp')
    editor.press('Enter')
    expect(editor).to_have_value('请检查 "./路径目录/中文 report.txt"')
    expect(editor).to_be_focused()
    # Bare filename and selection by mouse, without executing/sending.
    editor.fill('readme-')
    editor.press('Tab')
    expect(popup.get_by_role('option')).to_have_count(2)
    popup.get_by_role('option', name='readme-two.md 文件', exact=True).click()
    expect(editor).to_have_value('readme-two.md')
    editor.fill('!cat "./路径目录/中文')
    editor.press('Tab')
    expect(editor).to_have_value('!cat "./路径目录/中文 report.txt"')
    editor.fill(r'查看 ./路径目录/中文\ r')
    editor.press('Tab')
    expect(editor).to_have_value('查看 "./路径目录/中文 report.txt"')
    editor.fill('查看 ./linked')
    editor.press('Tab')
    expect(editor).to_have_value('查看 ./linked-dir/')
    editor.fill('查看 ./.hid')
    editor.press('Tab')
    expect(editor).to_have_value('查看 ./.hidden-note')
    editor.fill('查看 ' + str(work / 'readme-o'))
    editor.press('Tab')
    expect(editor).to_have_value('查看 ' + str(work / 'readme-one.md'))
    editor.fill('查看 ../' + work.name + '/readme-o')
    editor.press('Tab')
    # Parent traversal preserves spelling; quote if the fixture cwd has spaces.
    expect(editor).to_have_value('查看 ../' + work.name + '/readme-one.md')
    editor.fill('查看 ./readme-o 之后继续')
    editor.press('Home')
    for _ in range(len('查看 ./readme-o')):
        editor.press('ArrowRight')
    editor.press('Tab')
    expect(editor).to_have_value('查看 ./readme-one.md 之后继续')
    editor.fill('查看 ./readme-')
    editor.press('Tab')
    expect(popup).to_be_visible()
    editor.press('Escape')
    expect(popup).to_have_count(0)
    expect(editor).to_have_value('查看 ./readme-')
    editor.fill('./')
    editor.press('Tab')
    expect(popup.get_by_role('option')).to_have_count(4)
    expect(popup).not_to_contain_text('.hidden-note')
    editor.press('Escape')
    editor.fill('./does-not-exist')
    editor.press('Tab')
    expect(popup).to_contain_text('没有匹配的路径')
    editor.press('Escape')
    editor.fill('./missing-parent/file')
    editor.press('Tab')
    expect(popup).to_contain_text('路径补全失败')
    editor.press('Escape')
    # A delayed real request must not replace later edits.
    held = []
    def hold(route):
        held.append((route, route.fetch()))
    page.route('**/api/session/conversation/complete-path?*', hold)
    editor.fill('./readme-o')
    editor.press('Tab')
    expect(popup).to_contain_text('正在读取路径')
    page.wait_for_timeout(150)
    assert held
    editor.fill('后续输入保留')
    for route, response in held:
        route.fulfill(response=response)
    page.unroute('**/api/session/conversation/complete-path?*', hold)
    expect(popup).to_have_count(0)
    expect(editor).to_have_value('后续输入保留')
    editor.fill('./readme-o')
    editor.press('ControlOrMeta+A')
    editor.press('Tab')
    expect(editor).to_have_value('./readme-o')
    expect(popup).to_have_count(0)
    # Leave a completed path for caller's real save/reload/send checks.
    editor.fill('请检查 ./readme-o')
    editor.press('Tab')
    expect(editor).to_have_value('请检查 ./readme-one.md')
